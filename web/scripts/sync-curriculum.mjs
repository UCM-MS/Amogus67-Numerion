import { readFile, writeFile } from 'node:fs/promises';
// Both clients use the same reviewed academy curriculum. No editor or paid assets are bundled.
const source = JSON.parse(await readFile(new URL('../../unity/Assets/Lumen/Resources/Content/curriculum.json', import.meta.url), 'utf8'));
const subjects = ['math', 'science', 'nature', 'history', 'language', 'technology'];
const questions = source.Questions.map(q => ({
  id: q.Id, subject: subjects[q.Subject], ageBand: q.AgeBand, difficulty: q.Difficulty,
  title: `${source.Sections[q.Subject].Name} · ${q.Difficulty}/4`, question: q.Prompt,
  options: q.Options.map((label, i) => ({ id: String.fromCharCode(97 + i), label })),
  answer: String.fromCharCode(97 + q.CorrectOption), explanation: q.Explanation,
  hint: 'Rozdeľ si úlohu na menšie kroky. Pozorne porovnaj všetky možnosti.', sourceUrl: q.SourceUrl
}));
await writeFile(new URL('../public/curriculum.js', import.meta.url), `// Shared with the native Unity academy. Generated by scripts/sync-curriculum.mjs.\nexport const AGE_QUESTIONS = ${JSON.stringify(questions, null, 2)};\n`);
console.log(`Shared curriculum: ${questions.length} questions, ${subjects.length} subjects, four age bands.`);
